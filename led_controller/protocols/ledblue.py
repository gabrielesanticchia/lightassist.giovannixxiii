from __future__ import annotations

from .base import LedProtocol


class LedBlueProtocol(LedProtocol):
    aliases = ("LEDBLUE", "LEDBLUE-")
    effect_names = [f"LedBlue {i}" for i in range(8)]

    def power(self, enabled: bool) -> bytes:
        header = bytes([0x33, 0xAA])
        payload = bytes([0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00])
        return header + payload

    def rgb(self, r: int, g: int, b: int) -> bytes:
        header = bytes([0x33, 0xAA])
        payload = bytes([0x02, r, g, b, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00])
        return header + payload

    def brightness(self, value: int) -> bytes:
        value = max(0, min(100, value))
        header = bytes([0x33, 0xAA])
        payload = bytes([0x03, value, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00])
        return header + payload

    def effect(self, code: int) -> bytes:
        header = bytes([0x33, 0xAA])
        payload = bytes([0x04, code % 256, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00])
        return header + payload
